#!/usr/bin/env node
// Generates the hyphenation that js/hyphenate.js uses, as RequireJS modules:
//
//   npm run build-hyphenation
//
// js/hypher.js is Hypher (the hypher package, which jgabc's propers tool uses too), and
// js/hyphenation/<lang>.js are the patterns for each language: Latin from la.js here (jgabc's),
// the others from the hyphenation.<lang> packages that Hypher uses.  Don't edit the output.
'use strict';
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..', '..');
// Each module, by the code js/hyphenate.js asks for, and where its patterns come from.
var LANGUAGES = [
  {code: 'la', source: path.join(__dirname, 'la.js'), from: "jgabc's propers tool (patterns/la-hypher.js)"},
  {code: 'en', source: 'hyphenation.en-us'},
  {code: 'fr', source: 'hyphenation.fr'},
  {code: 'es', source: 'hyphenation.es'},
  {code: 'it', source: 'hyphenation.it'},
  {code: 'pt', source: 'hyphenation.pt'},
  {code: 'pl', source: 'hyphenation.pl'}
];

var write = function(file, text) {
  fs.writeFileSync(path.join(root, file), text);
  console.log('wrote ' + file);
};

var hypher = fs.readFileSync(require.resolve('hypher/lib/hypher.js'), 'utf8');
var hypherVersion = require('hypher/package.json').version;
write('js/hypher.js',
  '// Hypher ' + hypherVersion + ', Copyright (c) 2011, Bram Stein (BSD license, node_modules/hypher/BSD.txt),\n' +
  '// as a RequireJS module.  Generated by tools/hyphenation/build.js: don\'t edit.\n' +
  'define(function() {\n' +
  'var module = {exports: null};\n' +
  hypher.trim() + '\n' +
  'return module.exports;\n' +
  '});\n');

fs.mkdirSync(path.join(root, 'js', 'hyphenation'), {recursive: true});
LANGUAGES.forEach(function(l) {
  var language = require(l.source);
  var from = l.from;
  if(!from) {
    var pkg = require(l.source + '/package.json');
    from = 'the ' + pkg.name + ' ' + pkg.version + ' package';
  }
  write('js/hyphenation/' + l.code + '.js',
    '// Hyphenation patterns for Hypher, from ' + from + '.\n' +
    '// Generated by tools/hyphenation/build.js: don\'t edit.\n' +
    'define(' + JSON.stringify({
      leftmin: language.leftmin,
      rightmin: language.rightmin,
      exceptions: language.exceptions,
      patterns: language.patterns
    }, null, 1) + ');\n');
});
